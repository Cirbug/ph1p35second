#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_crc_par2.py
  生成 crc16_par2.v —— 每时钟处理 2 字节的并行 CRC-16/CCITT-FALSE

  原理：CRC 对输入是线性的（GF(2) 上），所以可以把位串行 LFSR
        展开成"输出位 = 若干输入位的异或"。这里用符号运算求这个矩阵，
        再直接打印成 assign 语句，避免手推出错。

  用法： python gen_crc_par2.py > ../uisrc/01_rtl/csi2/crc16_par2.v
"""

NB = 2  # 每拍字节数

# ---------------------------------------------------------------
# 符号表示：用 Python 整数当"位掩码"，第 i 位表示第 i 个输入
#   bit 0..15   -> I_crc[0..15]
#   bit 16..23  -> I_data[15:8]   (先处理的字节)
#   bit 24..31  -> I_data[7:0]    (后处理的字节)
# ---------------------------------------------------------------
def crc_init():
    return [1 << i for i in range(16)]          # s[i] = 输入 i


def crc_byte(s, data_bits):
    """把 8 个数据位（掩码列表，MSB 先）打进状态"""
    for i in range(7, -1, -1):
        fb = s[15] ^ data_bits[i]
        s = [0] + s[:15]                        # 左移一位
        for j in (0, 5, 12):                    # 异或 0x1021
            s[j] ^= fb
    return s


def build():
    s = crc_init()
    for k in range(NB):
        # V = {I_data, I_crc}  ->  V[16+j] = I_data[j], V[31] = I_data[15]
        # 高字节 b0 = I_data[15:8]，其 bit i 对应 V[24+i]
        # 低字节 b1 = I_data[7:0]，其 bit i 对应 V[16+i]
        base = 24 if k == 0 else 16
        bits = [1 << (base + i) for i in range(8)]
        s = crc_byte(s, bits)
    return s


def main():
    masks = build()
    print("//==========================================================================")
    print("// crc16_par2.v  -- AUTO-GENERATED by tools/gen_crc_par2.py, do not edit")
    print("//")
    print("//   CRC-16/CCITT-FALSE, 2 bytes per clock (parallel / unrolled)")
    print("//   poly 0x1021, init 0xFFFF, no reflection, no final xor")
    print("//")
    print("//   Semantics identical to feeding I_data[15:8] first, then I_data[7:0]")
    print("//   i.e. byte order is high byte -> low byte")
    print("//==========================================================================")
    print("module crc16_par2 (")
    print("    input  wire [15:0] I_crc,     // current CRC state")
    print("    input  wire [15:0] I_data,    // 2 bytes, high byte processed first")
    print("    output wire [15:0] O_crc      // updated CRC")
    print(");")
    print()
    print("    wire [31:0] V = { I_data, I_crc };   // V[15:0]=crc, V[31:16]=data")
    print()
    for i, m in enumerate(masks):
        if m == 0:
            print("    assign O_crc[%2d] = 1'b0;" % i)
        else:
            print("    assign O_crc[%2d] = ^(V & 32'h%08X);" % (i, m))
    print()
    print("endmodule")


if __name__ == "__main__":
    main()
