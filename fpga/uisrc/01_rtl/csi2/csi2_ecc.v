//==========================================================================
// csi2_ecc.v
//   CSI-2 / DSI 包头纠错码（6bit Hamming + 1bit 偶校验）
//
//   输入 24bit：{DI[7:0], WC[15:0]}
//   输出  8bit：{P7, P6, P5, P4, P3, P2, P1, P0}
//           P6 固定 0（保留位）
//           P7 = 24 位数据的偶校验
//
//   构造方式：把 24 个数据位映射到 32bit 码字中的非 2 次幂位置
//             （3,5,6,7,9..15,17..29），P0..P4 位于 1,2,4,8,16。
//             每个数据位的 syndrome 即其位置值，天然互不相同且非零。
//
//   ⚠ 注意：本实现对"单比特错误可纠"是完整自洽的（tb 已验证 24 个
//     syndrome 唯一）。但 MIPI 规范附录给出的列分配未逐位核对过，
//     若将来要接第三方接收端（会校验 ECC），需按规范再核对一遍。
//     当前链路 A 板解码器不校验 ECC/CRC，不影响出图。
//==========================================================================
module csi2_ecc (
    input  wire [23:0] I_hdr,
    output wire [7:0]  O_ecc
);

    wire [23:0] d = I_hdr;

    assign O_ecc[0] = ^{d[0],  d[1],  d[3],  d[4],  d[6],  d[8],  d[10],
                        d[11], d[13], d[15], d[17], d[19], d[21], d[23]};

    assign O_ecc[1] = ^{d[0],  d[2],  d[3],  d[5],  d[6],  d[9],  d[10],
                        d[12], d[13], d[16], d[17], d[20], d[21]};

    assign O_ecc[2] = ^{d[1],  d[2],  d[3],  d[7],  d[8],  d[9],  d[10],
                        d[14], d[15], d[16], d[17], d[22], d[23]};

    assign O_ecc[3] = ^{d[4],  d[5],  d[6],  d[7],  d[8],  d[9],  d[10],
                        d[18], d[19], d[20], d[21], d[22], d[23]};

    assign O_ecc[4] = ^{d[11], d[12], d[13], d[14], d[15], d[16], d[17],
                        d[18], d[19], d[20], d[21], d[22], d[23]};

    // P5 在当前列分配下无数据位，保持 0
    assign O_ecc[5] = 1'b0;

    // P6 保留位
    assign O_ecc[6] = 1'b0;

    // P7：24 位数据偶校验
    assign O_ecc[7] = ^{d[0],  d[1],  d[2],  d[3],  d[4],  d[5],  d[6],  d[7],
                        d[8],  d[9],  d[10], d[11], d[12], d[13], d[14], d[15],
                        d[16], d[17], d[18], d[19], d[20], d[21], d[22], d[23]};

endmodule
